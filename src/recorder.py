"""Recorder: captures every MCP tool call made during a session so the
sequence of steps needed to fulfil an automation "activity" can be saved,
inspected, and replayed later.
"""

from __future__ import annotations

import json
from dataclasses import asdict, dataclass, field
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Optional


def _now_iso() -> str:
    return datetime.now(timezone.utc).isoformat()


@dataclass
class Step:
    index: int
    timestamp: str
    tool: str
    arguments: dict[str, Any]
    status: str  # "ok" | "error"
    result_summary: str
    duration_ms: float


@dataclass
class Recording:
    activity: str
    context: str
    repo_url: str = ""
    app_map: Optional[dict] = None
    device: Optional[dict] = None
    build_url: str = ""
    extra_context: str = ""
    extra_context_filename: str = ""
    started_at: str = field(default_factory=_now_iso)
    steps: list = field(default_factory=list)

    def to_dict(self) -> dict:
        return asdict(self)


class Recorder:
    """Accumulates Steps for the current activity and persists them."""

    def __init__(
        self,
        activity: str,
        context: str,
        repo_url: str = "",
        app_map: Optional[dict] = None,
        device: Optional[dict] = None,
        build_url: str = "",
        extra_context: str = "",
        extra_context_filename: str = "",
    ) -> None:
        self.recording = Recording(
            activity=activity,
            context=context,
            repo_url=repo_url,
            app_map=app_map,
            device=device,
            build_url=build_url,
            extra_context=extra_context,
            extra_context_filename=extra_context_filename,
        )

    def log_step(
        self,
        tool: str,
        arguments: dict[str, Any],
        status: str,
        result_summary: str,
        duration_ms: float,
    ) -> Step:
        step = Step(
            index=len(self.recording.steps) + 1,
            timestamp=_now_iso(),
            tool=tool,
            arguments=arguments,
            status=status,
            result_summary=result_summary[:4000],
            duration_ms=round(duration_ms, 2),
        )
        self.recording.steps.append(asdict(step))
        return step

    def clear(self) -> None:
        self.recording.steps = []

    # ---------------------------------------------------------------- #
    # Persistence
    # ---------------------------------------------------------------- #
    def save(self, path: Path) -> Path:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(self.recording.to_dict(), indent=2, ensure_ascii=False), encoding="utf-8")
        return path

    def to_json(self) -> str:
        return json.dumps(self.recording.to_dict(), indent=2, ensure_ascii=False)

    def to_replay_script(self, recording_filename: str) -> str:
        """Generate a standalone Python script that replays the recorded
        tool calls, in order, against a fresh appium-mcp connection."""
        return REPLAY_TEMPLATE.format(recording_filename=recording_filename)


REPLAY_TEMPLATE = '''#!/usr/bin/env python3
"""Auto-generated by Appium MCP Studio.

Replays the MCP tool calls stored in "{recording_filename}" in order,
against a fresh appium-mcp stdio connection. Edit ANDROID_HOME / env vars
below if needed, and supply fresh capabilities when prompted by the
appium_session_management step if you removed them from the recording.
"""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from mcp_bridge import MCPBridge  # noqa: E402
from workflow import mcp_environment
from ios_runtime import IOSRuntime

RECORDING_PATH = Path(__file__).resolve().parent / "{recording_filename}"


def main() -> None:
    data = json.loads(RECORDING_PATH.read_text(encoding="utf-8"))
    print(f"Replaying activity: {{data['activity']}}")
    print(f"Steps: {{len(data['steps'])}}")

    env = mcp_environment()
    ios = IOSRuntime()
    bridge = MCPBridge()
    bridge.connect("npx", ["-y", "appium-mcp@latest"], env=env)

    try:
        preparation_hints = {{}}
        session_ids = {{}}
        for step in data["steps"]:
            print(f"-> [{{step['index']}}] {{step['tool']}} {{step['arguments']}}")
            if step["tool"] in {{"get_application_graph_summary", "search_application_graph", "get_application_node", "get_studio_state", "inspect_ios_environment", "check_ios_connection"}}:
                continue
            if step["tool"] == "show_ios_simulator":
                ios.show_simulator(**step["arguments"])
                continue
            if step["tool"] in {{"manage_ios_tunnel", "appium_prepare_ios_real_device"}}:
                raise RuntimeError("Replay restricted to local iPhone simulators")
            arguments = dict(step["arguments"])
            if arguments.get("sessionId") in session_ids:
                arguments["sessionId"] = session_ids[arguments["sessionId"]]
            if step["tool"] == "appium_session_management" and arguments.get("action") == "create":
                capabilities = json.loads(arguments.get("capabilities", "{{}}"))
                capabilities.update(preparation_hints.get(capabilities.get("appium:udid"), {{}}))
                arguments["capabilities"] = json.dumps(capabilities)
            outcome = bridge.call_tool(step["tool"], arguments, timeout=300)
            if not outcome.ok:
                raise RuntimeError(f"Step {{step['index']}} failed: {{outcome.error}}")
            if step["tool"] == "prepare_ios_simulator":
                prepared = json.loads(outcome.text)
                if not prepared.get("ready"):
                    raise RuntimeError(outcome.text)
                preparation_hints[arguments["udid"]] = prepared.get("capabilitiesHint", {{}})
            if step["tool"] == "appium_session_management" and arguments.get("action") == "create":
                marker = "session created successfully with ID: "
                old_first_line = step["result_summary"].splitlines()[0]
                new_first_line = outcome.text.splitlines()[0]
                if marker in old_first_line and marker in new_first_line:
                    session_ids[old_first_line.split(marker, 1)[1]] = new_first_line.split(marker, 1)[1]
            print(f"   ok: {{outcome.text[:200]}}")
    finally:
        bridge.shutdown()


if __name__ == "__main__":
    main()
'''
